# ── 자기검사 넷 ───────────────────────────────────────────
def 자검사(im):
    """**그림이 사람으로 읽히는가**를 숫자로 확인한다. 미달이면 멈춘다."""
    a = np.array(im)[:, :, 3] > 128
    결과 = []

    h, w = a.shape
    행 = a.sum(axis=1)
    채움 = a.sum() / (h * w)
    결과.append(("빈 그림이 아닌가", None if 0.10 < 채움 < 0.60
                 else "화면의 %.0f%% 를 채운다" % (채움 * 100)))

    # 위에서 8% 는 머리 — 좁아야 한다. 아래 10% 는 치마 — 넓어야 한다
    머리폭 = 행[:int(h * 0.08)].max() / w
    치마폭 = 행[int(h * 0.90):int(h * 0.98)].max() / w
    결과.append(("머리가 치마보다 좁은가",
                 None if 머리폭 < 치마폭 * 0.5
                 else "머리 %.2f · 치마 %.2f" % (머리폭, 치마폭)))

    # 허리가 어깨보다 좁아야 사람으로 읽힌다
    어깨 = 행[int(h * 0.26):int(h * 0.34)].max()
    허리 = 행[int(h * 0.43):int(h * 0.47)].max()
    결과.append(("허리가 어깨보다 좁은가",
                 None if 허리 < 어깨 else "어깨 %d · 허리 %d" % (어깨, 허리)))

    # 세로로 끊긴 데가 없어야 한다 (머리~치마단이 한 덩어리)
    빈줄 = int((행[int(h * 0.02):int(h * 0.97)] == 0).sum())
    결과.append(("몸이 끊기지 않았는가",
                 None if 빈줄 == 0 else "빈 줄 %d 개" % 빈줄))

    # ── ★ 여기부터가 「사람으로 읽히는가」 (2026-08-24 신설) ──────
    #
    # **앞의 넷을 통과한 그림이 「체스 말」이었다.** 검수자가 걸어가는 실제 사람과
    # 견주고서야 드러났다. **검사가 무르면 통과가 아무 뜻이 없다.**
    # **가장 긴 검은 토막의 길이**를 잰다 — 「검은 픽셀 수」가 아니다.
    # 팔을 몸 옆으로 뻗게 그렸더니 **팔 픽셀이 허리 폭에 섞여** 검사가 틀렸다.
    def 몸통폭(y0, y1):
        가장 = 0
        for y in range(y0, y1):
            줄, n, best = a[y], 0, 0
            for v in 줄:
                n = n + 1 if v else 0
                if n > best:
                    best = n
            가장 = max(가장, best)
        return 가장
    허 = 몸통폭(int(h * 0.41), int(h * 0.45))
    엉 = 몸통폭(int(h * 0.50), int(h * 0.56))
    결과.append(("허리가 엉덩이보다 뚜렷이 좁은가",
                 None if 허 < 엉 * 0.85 else "허리 %d · 엉덩이 %d (85%% 미만이어야)" % (허, 엉)))

    # 사람은 가늘다. 키 대비 최대 폭이 3분의 1을 넘으면 덩어리다
    비 = h / max(1, 행.max())
    결과.append(("키가 폭의 세 배 이상인가",
                 None if 비 >= 3.0 else "%.1f 배 — 너무 넓적하다" % 비))

    # **팔과 몸 사이에 틈이 있는가** — 한 줄 안에 검은 덩어리가 둘로 갈리는 데가 있어야 한다
    갈림 = 0
    for y in range(int(h * 0.20), int(h * 0.46)):
        줄 = a[y]
        덩 = int(((~줄[:-1]) & 줄[1:]).sum())     # 흰→검 로 바뀌는 횟수
        if 덩 >= 2:
            갈림 += 1
    결과.append(("팔과 몸 사이에 틈이 있는가",
                 None if 갈림 >= h * 0.03 else "갈린 줄 %d — 통짜로 보인다" % 갈림))

    print("=== 자기검사 ===")
    for 이, 틀 in 결과:
        print("  %-24s %s" % (이, "OK" if 틀 is None else "✗ " + 틀))
    if any(x for _, x in 결과):
        sys.exit("\n**실루엣이 사람으로 안 읽힌다. 파일을 내지 않는다.**")
    print("  → **넷 다 통과**\n")



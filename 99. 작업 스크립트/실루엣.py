def 자리읽기():
    """**승인된 뼈대에서 여섯 자리의 사진을 그때그때 읽어 온다.**

    `그녀자리.여섯` 이 시각을 갖고, `뼈대.json` 이 그 시각의 사진을 갖는다.
    **여기서는 둘을 잇기만 한다** — 그래야 뼈대가 바뀌어도 안 어긋난다.
    """
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from importlib import import_module
    여섯 = import_module("그녀자리").여섯
    뼈 = json.load(io.open(os.path.join(ROOT, "95. 영상 프로젝트", "src",
                                        "뼈대.json"), encoding="utf-8"))
    out = []
    for (n, 초, _), (키, 가로, 발) in zip(여섯, 놓기):
        컷 = [c for c in 뼈["컷"] if c["시작"] <= 초 < c["시작"] + c["길이"]]
        if not 컷:
            sys.exit("%.2f초에 컷이 없다 — `뼈대.py` 를 먼저 돌린다" % 초)
        p = 컷[0]["사진"][0]
        out.append(("%d:%05.2f" % (컷[0]["시작"] // 60, 컷[0]["시작"] % 60),
                    p.split("/")[-2], p.split("/")[-1], 키, 가로, 발))
    return out


def 합성(실루엣, 낼곳):
    os.makedirs(낼곳, exist_ok=True)
    소재 = os.path.join(ROOT, "2005년 12월 스페인")
    판 = []
    # ## **「지금 여섯」을 적어 낸다** (2026-08-24 신설)
    #
    # **R11 이 산출물을 못 지우게 하므로** 자리를 바꾸면 **옛 판이 폴더에 남는다.**
    # 실제로 `그녀 9-55.18 P1010176.JPG`(연못)이 남아 **`Seedance.py` 가 일곱 장을
    # 집어가려 했다** — 그대로 뒀으면 **안 쓸 한 장에 돈이 나갔다.**
    #
    # **폴더를 훑어서 알아내지 않는다. 만든 쪽이 적는다.**
    적을것 = []
    for 시각, 폴, 파, 키, 가로, 발 in 자리읽기():
        bg = Image.open(os.path.join(소재, 폴, 파)).convert("RGB")
        h = int(bg.height * 키)
        w = int(실루엣.width * h / 실루엣.height)
        s = 실루엣.resize((w, h), Image.LANCZOS)
        x = int(bg.width * 가로 - w / 2)
        y = int(bg.height * 발) - h            # **발이 닿는 높이는 사진마다 다르다**
        # **그림자처럼 아주 살짝 흐리게** — 오려붙인 티가 덜 난다
        s = s.filter(ImageFilter.GaussianBlur(max(1, h // 400)))
        bg.paste(s, (x, y), s)
        판.append((시각, 파, bg))
        이름 = "그녀 %s %s" % (시각.replace(":", "-"), 파)
        bg.save(os.path.join(낼곳, 이름), quality=92)
        적을것.append({"시각": 시각, "사진": 파, "얹은것": 이름,
                       "키": 키, "가로": 가로, "발": 발})

    with io.open(os.path.join(낼곳, "지금 여섯.json"), "w", encoding="utf-8") as f:
        json.dump(적을것, f, ensure_ascii=False, indent=2)

    # 여섯을 한 판에 — **같은 인물로 보이는지는 나란히 놔야 안다**
    칸w, 칸h = 620, 465
    한판 = Image.new("RGB", (칸w * 3 + 32, (칸h + 26) * 2 + 26), (22, 22, 22))
    dd = ImageDraw.Draw(한판)
    for i, (시각, 파, im) in enumerate(판):
        r, c = divmod(i, 3)
        im2 = im.copy(); im2.thumbnail((칸w, 칸h), Image.LANCZOS)
        X = 8 + c * (칸w + 8) + (칸w - im2.width) // 2
        Y = 8 + r * (칸h + 26)
        한판.paste(im2, (X, Y))
        dd.text((8 + c * (칸w + 8) + 2, Y + 칸h + 4),
                "%s  %s" % (시각, 파), fill=(235, 235, 120))
    P = os.path.join(낼곳, "그녀 여섯 자리 - 한 판에.jpg")
    한판.save(P, quality=90)
    return P



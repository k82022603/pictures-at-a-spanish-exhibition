def 곡선(점들, n=60):
    """점 몇 개를 부드러운 곡선으로 잇는다 (Catmull–Rom)."""
    P = np.asarray(점들, float)
    P = np.vstack([P[0], P, P[-1]])
    out = []
    for i in range(len(P) - 3):
        p0, p1, p2, p3 = P[i:i + 4]
        t = np.linspace(0, 1, n)[:, None]
        out.append(0.5 * ((2 * p1) + (-p0 + p2) * t
                          + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t ** 2
                          + (-p0 + 3 * p1 - 3 * p2 + p3) * t ** 3))
    return np.vstack(out)



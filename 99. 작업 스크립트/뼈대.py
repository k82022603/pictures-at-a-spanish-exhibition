def 등급순(사진들):
    """**A 를 먼저, 그 다음 B. C 는 안 쓴다.** (WBS 2.1 → 3.2)

    처음에는 **파일 이름 순**으로 넣었다. 자리와 시간만 정하는 단계라
    「어느 사진이 좋은가」는 뒤로 미룬 것이었는데, **론다는 23개 중 4개만 쓰므로
    이름 순으로 넣으면 좋은 사진이 안 쓰일 확률이 그만큼 높다.**

    **등급은 눈이 매긴 것이다** — [`등급부여.py`](<등급부여.py>) 가 갖고 있고
    이 도구는 **읽기만 한다.** 숫자로 다시 매기지 않는다.

    같은 등급 안에서는 **파일 이름 순 = 찍은 순서**다. 여행의 시간 순서가
    화면의 순서가 된다.
    """
    순위 = {"A": 0, "B": 1}
    쓸것 = [a for a in 사진들 if a["등급"] in 순위]
    # **검수자가 지목한 것은 등급보다 앞선다** (`혼자`, 2026-08-24).
    # 지목했는데 등급에 밀려 안 나오면 지목한 뜻이 없다 — 실제로 `P1010143` 이
    # 그라나다 41 화면 중 26 을 쓰는 컷에서 밀려 **통째로 빠졌었다.**
    쓸것.sort(key=lambda a: (0 if a["정렬키"] in 혼자 else 1,
                             순위[a["등급"]], a["정렬키"]))
    return 쓸것


def 컷하나(번호, 시작, 길이, 화면, 재사용=False):
    """**컷 하나를 만든다.**

    `방향` 을 함께 실어 보내는 것이 중요하다 — 세로 사진을 가로 화면에 꽉 채우면
    **위아래가 잘려 나가서** 그리는 쪽에서 다르게 다뤄야 한다. 그리는 쪽이
    **경로 이름으로 추측하게 두면 안 된다.**
    """
    c = {"악장": 번호, "시작": round(시작, 4), "길이": round(길이, 4),
         "종류": 화면["종류"],
         "사진": [x["경로"] for x in 화면["사진"]],
         "방향": 화면["사진"][0]["방향"],
         "도시": 화면["사진"][0]["도시"],
         "재사용": bool(재사용)}
    보정들 = [보정.get(x["파일"]) for x in 화면["사진"]]
    if any(보정들):
        c["보정"] = 보정들          # 사진마다 하나씩. 없으면 null
    if any(x["파일"] in 줌없이 for x in 화면["사진"]):
        c["줌없이"] = True          # **그리는 쪽은 이 표시만 보고 따른다**
    return c


def 화면만들기(사진들, 도시):
    """**한 도시의 사진을 「화면」 목록으로 바꾼다.**

    가로는 한 장이 한 화면이고, **세로는 남는 도시에 한해 둘씩 묶는다**
    (`00` 기획서의 멀티패널). 홀수로 남는 한 장은 그대로 한 화면이다.
    """
    가로 = [a for a in 사진들 if a["방향"] == "가로"]
    # **`혼자` 에 적힌 세로는 짝을 안 짓는다** (검수자 지목, 2026-08-24)
    세로 = [a for a in 사진들 if a["방향"] == "세로" and a["정렬키"] not in 혼자]
    홀로 = [a for a in 사진들 if a["방향"] == "세로" and a["정렬키"] in 혼자]
    # **`혼자` 로 지목된 것을 맨 앞에 놓는다.** `등급순()` 이 앞으로 보내 놨어도
    # 여기서 가로/세로로 다시 나누면 그 순서가 흐트러진다 — 실제로 `P1010143` 이
    # 가로 40장 뒤로 밀려 **또 안 나왔다.**
    단일 = [{"종류": "단일", "사진": [a]} for a in 홀로
            + [b for b in 가로 if b["정렬키"] in 혼자]
            + [b for b in 가로 if b["정렬키"] not in 혼자]]
    묶음 = []
    if 도시 in 패널도시:
        for i in range(0, len(세로) - 1, 2):
            묶음.append({"종류": "멀티패널", "사진": [세로[i], 세로[i + 1]]})
        if len(세로) % 2:
            단일.append({"종류": "단일", "사진": [세로[-1]]})
    else:
        단일 += [{"종류": "단일", "사진": [a]} for a in 세로]

    # ── **섞는다.** 앞에서부터 필요한 만큼만 쓰기 때문이다 ────────────
    #
    # 가로를 먼저 다 늘어놓고 뒤에 묶음을 붙이면, **필요한 만큼 잘랐을 때
    # 묶음이 통째로 잘려 나간다.** 그러면 세로 사진 107장이 거의 안 나오고,
    # 화면당 두 장을 담아 더 많이 보여주려던 것이 무의미해진다.
    #
    # **비율대로 번갈아 끼운다** — 어디를 잘라도 섞인 채로 남는다.
    화면, i, j = [], 0, 0
    전체 = len(단일) + len(묶음)
    for k in range(전체):
        묶음차례 = 묶음 and (j * 전체 < (k + 1) * len(묶음))
        if 묶음차례:
            화면.append(묶음[j]); j += 1
        elif i < len(단일):
            화면.append(단일[i]); i += 1
        elif j < len(묶음):
            화면.append(묶음[j]); j += 1
    return 화면



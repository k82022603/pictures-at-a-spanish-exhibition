# -*- coding: utf-8 -*-
"""**0악장을 조립한다 — 원본 앞부분 + Extend 종결 + 잔향 꼬리.**

2026-08-22. **검수자가 「0:02~0:30 잡음」을 듣고 잡아냈다.**

## 무엇이 문제였나

Suno `Extend` 는 화면에 **`KEEP`(0~43초) / `RECREATE`(43~50초)** 라고 표시한다.
**그런데 `KEEP` 구간도 그대로 두지 않는다.** 실측하면 —

| 구간 | 원본 고역(4 kHz↑) | Extend | 차이 |
|---|---|---|---|
| 0~30초 | −18 ~ −23 dB | **−25 ~ −37 dB** | **−7 ~ −23 dB** |
| 30~42초 | −18 ~ −22 | −17 ~ −20 | ±2 |
| 42초~ | — | −10 ~ −18 | 새로 만든 부분 |

**앞 30초만 고역이 깎여 나간다.** 먹먹해지고, 그것이 「잡음」으로 들린다.

> **내가 「KEEP 이니 원본 그대로겠지」 하고 재지 않았다.**
> **화면의 낱말을 믿고 소리를 안 쟀다.** 그래서 이 파일이 있다.

## 그래서 어떻게 하나

**원본을 쓸 수 있는 데까지 쓰고, 종결만 Extend 에서 가져온다.**
이음매는 **두 소스의 고역이 가장 비슷한 자리**(37~40초, 차이 0.7 dB)에 둔다.
"""
import sys

import numpy as np

sys.path.insert(0, ".")
from 꼬리늘리기 import 읽기, 쓰기, 꼬리  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8")

이음 = 39.0        # 원본을 여기까지 쓴다. 두 소스의 고역 차이가 0.7 dB 인 자리
끝 = 68.00         # Extend 가 맺는 자리 (검수자 채택)
페이드 = 0.30      # 이음매 크로스페이드. 소스가 다르므로 20 ms 보다 길게
RT60 = 2.2         # 잔향 꼬리 → 2.53초 (검수자 채택 「짧게 +2초」)


def 고역(x, sr, a, b):
    s = x[int(a * sr):int(b * sr)].mean(axis=1)
    S = np.abs(np.fft.rfft(s * np.hanning(len(s)))) ** 2
    f = np.fft.rfftfreq(len(s), 1 / sr)
    return 10 * np.log10(S[f >= 4000].sum() / S.sum() + 1e-20)


if __name__ == "__main__":
    N = "../산출물/20260822 - 0악장을 다시 만든다"
    sr, orig = 읽기(N + "/받은 것 - 0악장/0악장 Suno-02.wav")
    _, ext = 읽기(N + "/받은 것 - 0악장 Extend/0악장 Extend-01 (43초부터).wav")

    # 크로스페이드는 **겹치는 구간**이므로 양쪽에서 절반씩 더 가져온다.
    # 그러지 않으면 겹친 만큼 음악이 짧아진다 (첫 판에서 0.3초를 잃었다).
    n = int(페이드 * sr)
    f = np.linspace(0, 1, n)[:, None]
    a = orig[: int(이음 * sr) + n // 2].copy()
    b = ext[int(이음 * sr) - n // 2: int(끝 * sr)]
    a[-n:] = a[-n:] * (1 - f) + b[:n] * f
    본편 = np.vstack([a, b[n:]])
    판 = np.vstack([본편, 꼬리(본편, sr, RT60)])

    P = N + "/받은 것 - 0악장 Extend/0악장 - 원본 앞부분 + 맺음 + 꼬리.wav"
    쓰기(P, sr, 판)

    print("0악장 조립 완료 — %.2f초 (원본 0~%.1f초 · Extend %.1f~%.1f초 · 꼬리 %.2f초)"
          % (len(판) / sr, 이음, 이음, 끝, len(판) / sr - 끝))
    print("\n[고친 것이 실제로 고쳐졌나 — 고역 비율]")
    잘못 = 읽기(N + "/받은 것 - 0악장 Extend/0악장 - 꼬리 짧게 +2초.wav")[1]
    for 이름, x in [("원본 Suno-02", orig), ("아까 낸 것 (잡음)", 잘못), ("★ 새로 조립한 것", 판)]:
        print("  %-20s 0:02~0:30 %6.1f dB · 0:30~0:39 %6.1f dB"
              % (이름, 고역(x, sr, 2, 30), 고역(x, sr, 30, 39)))
    m = 판.mean(axis=1)
    d = np.abs(np.diff(m))
    k = int(이음 * sr)
    print("\n[이음매 %.1f초 검사]" % 이음)
    print("  최대 도약 %.5f (전곡 99.99%% = %.5f)  %s"
          % (d[k - 480:k + 480].max(), np.percentile(d, 99.99),
             "OK" if d[k - 480:k + 480].max() <= np.percentile(d, 99.99) else "★튄다"))
    print("  앞 1초 고역 %.1f → 뒤 1초 %.1f dB  (차이 %.1f)"
          % (고역(판, sr, 이음 - 1, 이음), 고역(판, sr, 이음, 이음 + 1),
             고역(판, sr, 이음, 이음 + 1) - 고역(판, sr, 이음 - 1, 이음)))

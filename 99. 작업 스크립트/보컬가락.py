def 줄나누기(tr, hop=0.01, 침묵=0.55, 최소=2.5):
    """노래하는 구간을 찾아 줄로 묶는다.

    `침묵` 보다 길게 쉬면 줄이 바뀐 것으로 본다. 우리 줄은 8.6초이고
    줄 사이가 2초 넘게 비므로 넉넉하다.
    """
    on = tr > 0
    구간, i = [], 0
    while i < len(on):
        if not on[i]:
            i += 1
            continue
        j = i
        빈칸 = 0
        while j < len(on):
            if on[j]:
                빈칸 = 0
            else:
                빈칸 += 1
                if 빈칸 * hop > 침묵:
                    break
            j += 1
        끝 = j - 빈칸
        if (끝 - i) * hop >= 최소:
            구간.append((i * hop, 끝 * hop))
        i = j
    return 구간


def 줄맞추기(구간, tr, 목표=4, hop=0.01):
    """**우리는 줄이 넷인 것을 알고 있다.** 덜 나뉘었으면 더 쪼갠다.

    2026-08-20 개정. 첫 판에서 Suno 가 **55초를 끊지 않고** 불러 한 덩어리가
    36.7초로 잡혔다. 침묵 문턱을 낮추면 이번엔 잘못된 자리에서 쪼개진다.

    **개수를 아는 쪽에서 접근한다** — 가장 긴 덩어리를 그 안에서 **가장 깊게
    쉬는 자리**에서 자르기를, 넷이 될 때까지 되풀이한다.
    """
    구간 = list(구간)
    on = tr > 0
    while len(구간) < 목표:
        k = max(range(len(구간)), key=lambda i: 구간[i][1] - 구간[i][0])
        a, b = 구간[k]
        i0, i1 = int(a / hop), int(b / hop)
        # 안쪽에서 쉬는 자리들 — 가장자리 20%는 뺀다(줄 하나가 너무 짧아진다)
        여백 = int((i1 - i0) * 0.2)
        쉼, 시작 = [], None
        for i in range(i0 + 여백, i1 - 여백):
            if not on[i] and 시작 is None:
                시작 = i
            elif on[i] and 시작 is not None:
                쉼.append((i - 시작, 시작, i))
                시작 = None
        if not 쉼:
            break
        길이, s, e = max(쉼)
        가운데 = (s + e) / 2 * hop
        구간[k:k + 1] = [(a, 가운데 - 0.05), (가운데 + 0.05, b)]
    return 구간


# ══════════════════════ ③ 음절을 찾는다 ═══════════════════════════════
def 음절나누기(x, n=11, 최소간격=0.22):
    """줄 하나에서 음절 시작을 찾는다. **소리가 커지는 순간이 음절의 시작.**

    **문턱으로 세지 않고 「가장 센 n 개」를 고른다** (2026-08-20 개정).
    문턱 방식은 첫 판에서 **22개·61개·80개**를 찾았다 — 목소리마다 크기와
    또렷함이 달라 문턱 하나로는 안 맞는다. **우리는 몇 개인지 이미 알고
    있다(11개).** 모르는 것은 「어디인가」뿐이므로 **센 것부터 n 개**를
    집는 것이 맞다.

    `최소간격` 은 우리 선율의 가장 짧은 음(8분음표 0.48초)의 절반이다.
    그보다 가까운 둘은 **한 음절의 시작과 그 안의 잔결**이므로 뒤엣것을 버린다.
    """
    w = int(0.02 * SR)
    e = np.array([np.sqrt(np.mean(x[i:i + w] ** 2))
                  for i in range(0, len(x) - w, w)])
    e = e / (e.max() + 1e-12)
    # 「소리가 커지는 정도」 — 커질 때만 센다(작아지는 것은 음절의 시작이 아니다)
    d = np.diff(e, prepend=e[0]).clip(0)
    d[e < 0.06] = 0.0                            # 거의 무음인 자리는 안 본다
    후보 = [i for i in range(1, len(d) - 1)
            if d[i] >= d[i - 1] and d[i] > d[i + 1] and d[i] > 0]
    후보.sort(key=lambda i: -d[i])
    고른것 = []
    최소 = int(최소간격 / 0.02)
    for i in 후보:
        if all(abs(i - j) >= 최소 for j in 고른것):
            고른것.append(i)
        if len(고른것) >= n:
            break
    return sorted(i * 0.02 for i in 고른것)



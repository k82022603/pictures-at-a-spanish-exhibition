def 목표곡선(n, 음절수):
    """우리 격자에 놓인 목표 음 곡선. 음 경계에서 20 ms 만에 미끄러진다.

    **딱 끊으면 삐걱거린다.** 사람도 음을 옮길 때 아주 짧게 미끄러진다.
    """
    f = np.zeros(n)
    t0 = 0.0
    for m, b in TH_A:
        i, j = int(t0 / LINE_DUR * n), int((t0 + b * BT9) / LINE_DUR * n)
        f[i:j] = midi_hz(m)
        t0 += b * BT9
    f[f == 0] = midi_hz(TH_A[-1][0])
    k = max(1, int(0.020 * SR))
    return np.convolve(f, np.ones(k) / k, "same")


def 흔들림(y, hop=0.01, 창=0.15, 세기=0.50, 상한=50.0):
    """**부른 사람의 떨림만 뽑는다.** 음의 높낮이는 버리고 흔들림만 남긴다.

    목표 음을 그냥 넣으면 **자로 그은 것처럼 곧은 소리**가 난다. 실제로
    2026-08-20 첫 판이 떨림 **52센트 → 11센트** 로 떨어졌다 — 가락은 우리
    것이 됐는데 **사람이 부른 흔적이 지워졌다.**

    그래서 **부른 높이에서 그 언저리 평균을 뺀다.** 남는 것이 비브라토와
    미세한 흔들림이고, 그것을 목표 음에 얹으면 **가락은 우리 것이면서
    떨림은 그 사람 것**이 된다.
    """
    tr = 음높이.재기(y, hop=hop)
    c = np.zeros(len(tr))
    유성 = tr > 0
    if 유성.sum() < 5:
        return np.zeros(len(y))
    c[유성] = 1200.0 * np.log2(tr[유성] / 440.0)
    # 언저리 평균 — 이것이 「그 음의 중심」이다
    k = max(3, int(창 / hop))
    ker = np.ones(k) / k
    w = np.convolve(유성.astype(float), ker, "same")
    mid = np.convolve(c, ker, "same") / np.maximum(w, 1e-9)
    dev = np.where(유성, c - mid, 0.0) * 세기
    # **그대로 얹으면 넘친다.** 언저리 평균은 떨림뿐 아니라 **음이 옮겨가는
    # 움직임**도 담고 있어서, 첫 판이 떨림 86센트(원본 52)로 과했다.
    #
    # **⚠ 미결 (2026-08-20)** — 창을 0.12~0.30초로, 세기를 0.6~0.8로 훑어도
    # 떨림이 **84~95센트에서 안 움직였다.** 즉 이 값은 **여기서 얹는 흔들림이
    # 만드는 것이 아니다.** `창법실측.vibrato` 가 이런 소리(음이 계속 옮겨
    # 다니는 8.5초)를 어떻게 읽는지를 먼저 봐야 한다. **원인을 모르는 채로
    # 숫자를 맞추려고 값을 돌리지 않는다** — 그러면 무엇을 고친 것인지 모른다.
    dev = np.clip(dev, -상한, 상한)
    t = np.arange(len(y)) / SR
    return np.interp(t, np.arange(len(dev)) * hop, dev)


밴드 = [(150, 300), (300, 600), (600, 1200), (1200, 2400),
        (2400, 4800), (4800, 9600), (9600, 16000)]


def 대역비율(x):
    """옥타브 폭으로 나눠 어느 자리에 소리가 얼마나 있는지."""
    S = np.abs(np.fft.rfft(x)) ** 2
    f = np.fft.rfftfreq(len(x), 1.0 / SR)
    v = np.array([S[(f >= lo) & (f < hi)].sum() for lo, hi in 밴드])
    return v / max(1e-12, v.sum())


def 대역맞춤(y, 목표, 상한=24.0):
    """**낸 소리의 대역 분포를 원본에 맞춘다.**

    옥타브마다 얼마나 어긋났는지 재서 그만큼 깎거나 올린다. 한 대역을
    `상한` dB 넘게 건드리지 않는다 — 그 이상은 소리를 새로 만드는 것이지
    맞추는 것이 아니다.
    """
    지금 = 대역비율(y)
    Y = np.fft.rfft(y)
    f = np.fft.rfftfreq(len(y), 1.0 / SR)
    이득 = np.ones(len(f))
    for k, (lo, hi) in enumerate(밴드):
        if 지금[k] <= 1e-9 or 목표[k] <= 1e-9:
            continue
        d = 10.0 * np.log10(목표[k] / 지금[k])
        d = float(np.clip(d, -상한, 상한))
        이득[(f >= lo) & (f < hi)] = 10.0 ** (d / 20.0)
    # 대역 경계를 부드럽게 — 딱 끊으면 금속성 울림이 생긴다
    k = max(3, int(len(f) / 400))
    이득 = np.convolve(이득, np.ones(k) / k, "same")
    return np.fft.irfft(Y * 이득, len(y))


def 가락입히기(x, 음절):
    """줄 하나에 우리 가락을 입힌다. 반환 — (소리, 붙인 방식)"""
    n = int(LINE_DUR * SR)
    if len(음절) == len(TH_A):
        # **음절마다 제 음의 자리로 편다.** 가사와 음이 어긋나지 않는다
        경계 = [0.0] + 음절[1:] + [len(x) / SR]
        조각, t0 = [], 0.0
        for k, (m, b) in enumerate(TH_A):
            a, z = int(경계[k] * SR), int(경계[k + 1] * SR)
            조각.append(stretch(x[a:z], max(64, int(b * BT9 * SR))))
            t0 += b * BT9
        # ★ **이음매를 겹쳐서 잇는다** (2026-08-20). 그냥 붙이면 조각 끝과 다음
        # 조각 처음의 파형이 어긋나 **「딱」 하는 튀는 소리**가 난다. 그 봉우리
        # 하나 때문에 **봉우리와 몸통의 차이가 22 dB** 로 벌어졌고, 크기를
        # 맞출 때 리미터가 **몸통을 통째로 눌러** 안 들리게 만들었다.
        겹 = int(0.008 * SR)                     # 8 ms
        y = 조각[0]
        for 다음 in 조각[1:]:
            k = min(겹, len(y) // 2, len(다음) // 2)
            if k < 8:
                y = np.concatenate([y, 다음])
                continue
            f = np.linspace(0.0, 1.0, k)
            겹친 = y[-k:] * (1 - f) + 다음[:k] * f
            y = np.concatenate([y[:-k], 겹친, 다음[k:]])
        y = y[:n]
        y = np.pad(y, (0, max(0, n - len(y))))
        방식 = "음절 %d 개를 음마다 하나씩" % len(음절)
    else:
        y = stretch(x, n)
        방식 = "음절 %d 개(11 아님) — 줄 전체를 균등하게 폈다" % len(음절)
    # **높이를 새로 만들어 넣는다.** 여기가 이 도구의 핵심이다.
    # 목표 음에 **그 사람의 떨림**을 얹는다 — 안 얹으면 자로 그은 소리가 난다
    곡선 = 목표곡선(n, len(음절)) * 2.0 ** (흔들림(y) / 1200.0)
    원본대역 = 대역비율(y)
    y = resynth(y, 곡선, vib=0.0)
    # ★ **목소리의 몸통을 되살린다** (2026-08-20).
    #
    # `resynth` 는 성대를 **임펄스**로 흉내낸다. 임펄스는 배음이 전부 같은
    # 크기라 **실제 성대보다 훨씬 밝다.** 그래서 낸 소리는 에너지의 **67.7%가
    # 3.2~6.4 kHz**(쉭쉭거리는 자리)에 몰리고 **목소리의 몸통(200~800 Hz)이
    # 10.5%** 밖에 안 남았다. 원본은 그 자리가 **66.2%** 다.
    #
    # **미터는 크다고 찍는데 귀에는 안 들린다** — 검수자가 다섯 번 *"개미
    # 지나가는 소리"* 라고 한 것이 이것이다. 크기 문제가 아니라 **소리가 있는
    # 자리** 문제였다.
    #
    # 실제 성대는 옥타브마다 −12 dB 로 기운다. 그 기울기를 되돌려 준 뒤
    # **원본과 대역 분포를 맞춘다.**
    y = 대역맞춤(y, 원본대역)
    t = np.arange(n) / SR
    y *= np.clip(t / 0.03, 0, 1) * np.clip((LINE_DUR - t) / 0.06, 0, 1)
    return y, 방식



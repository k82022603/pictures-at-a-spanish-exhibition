D = {t[0]: t for t in T}
ES, EF = {}, {}


def solve(i):
    if i in EF:
        return EF[i]
    _, _, dur, pre, _ = D[i]
    ES[i] = max([solve(p) for p in pre], default=0.0)
    EF[i] = ES[i] + dur
    return EF[i]


for i in D:
    solve(i)

END = max(EF.values())

# backward pass
LF, LS = {}, {}
succ = {i: [] for i in D}
for i, (_, _, _, pre, _) in D.items():
    for p in pre:
        succ[p].append(i)


def back(i):
    if i in LS:
        return LS[i]
    LF[i] = min([back(s) for s in succ[i]], default=END)
    LS[i] = LF[i] - D[i][2]
    return LS[i]


for i in D:
    back(i)


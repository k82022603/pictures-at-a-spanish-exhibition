# -*- coding: utf-8 -*-
"""「없던 것도 그려 넣는다」기준 생성 비용을 계산한다.

**손으로 곱하지 않는다.** 이 프로젝트에서 손계산이 여러 번 틀렸다.
값의 출처는 전부 주석에 적는다.
"""
import sys
sys.stdout.reconfigure(encoding="utf-8")

# ── 화소당 단가가 정말 일정한가부터 확인한다 ──────────────────
# 공개된 값 셋으로 검산한다. 맞으면 1080p 를 계산해도 된다.
공개 = [("480p", 854, 480, 0.1028),      # OpenRouter 공개
        ("720p", 1280, 720, 1.16 / 5),   # CometAPI — 5초 $1.16
        ("4K",  3840, 2160, 2.08)]       # OpenRouter 공개
print("=== 화소당 단가가 일정한가 (초당가 ÷ 화소수) ===")
단가들 = []
for 이름, w, h, 초당 in 공개:
    u = 초당 / (w * h)
    단가들.append(u)
    print("  %-5s %7d 화소 · 초당 $%.4f → 화소당 %.4e" % (이름, w * h, 초당, u))
퍼짐 = (max(단가들) - min(단가들)) / min(단가들)
print("  → 셋의 차이 %.1f%% — %s" % (퍼짐 * 100,
      "**일정하다. 1080p 를 계산해도 된다**" if 퍼짐 < 0.02 else "일정하지 않다. 계산 금지"))
if 퍼짐 >= 0.02:
    sys.exit("화소당 단가가 일정하지 않다 — 1080p 추정을 하지 않는다")

화소당 = sum(단가들) / 3
초당_1080 = 화소당 * 1920 * 1080
print("\n  1080p 초당 $%.4f — **추정값이다. 공식 발표 없음**" % 초당_1080)

# ── 한 편(5초) 값 ──────────────────────────────────────
클립 = 5.0
값 = {
    "Seedance 480p":   0.1028 * 클립,
    "Seedance 720p":   1.16,                 # 공개값 그대로
    "Seedance 1080p":  초당_1080 * 클립,      # 추정
    "PixVerse (해상도 미확인)": 0.375,          # $0.30~0.45 의 가운데
}
print("\n=== 5초 한 편 값 ===")
for k, v in 값.items():
    print("  %-24s $%.2f" % (k, v))

# ── 몇 편이 필요한가 ────────────────────────────────────
# 전곡 619.84초. **4악장 세비야 96.1초는 V3 로 생성 금지**이므로 뺀다.
전곡, 세비야 = 619.84, 96.1
생성가능 = 전곡 - 세비야
단계 = [
    ("A  아껴 쓴다 — 그녀가 나오는 자리만",  15),
    ("B  중간 — 그녀 + 도시마다 핵심 몇 장", 40),
    ("C  전부 — 세비야 빼고 다",  int(생성가능 // 클립)),
]
print("\n=== 몇 편인가 (생성 가능한 길이 %.1f초 = 전곡 − 세비야) ===" % 생성가능)
for 이름, n in 단계:
    print("  %-34s %3d 편 · 화면의 %4.1f%%" % (이름, n, n * 클립 / 전곡 * 100))

# ── 다시 뽑는 횟수가 값을 정한다 ─────────────────────────
print("\n=== 예상 금액 (다시 뽑기 2.5배 기준) ===")
재시도 = 2.5
print("  %-34s %10s %10s %10s %10s" % ("", "480p", "**720p**", "1080p(추정)", "PixVerse"))
for 이름, n in 단계:
    g = n * 재시도
    print("  %-34s %10s %10s %10s %10s" % (
        이름,
        "$%.0f" % (g * 값["Seedance 480p"]),
        "**$%.0f**" % (g * 값["Seedance 720p"]),
        "$%.0f" % (g * 값["Seedance 1080p"]),
        "$%.0f" % (g * 값["PixVerse (해상도 미확인)"])))

print("\n=== 다시 뽑기 횟수를 바꿔 보면 (720p · 단계 B 40편) ===")
for r in (1.5, 2.0, 2.5, 3.0, 4.0):
    print("  %.1f 배 → %3.0f 편 생성 → $%.0f" % (r, 40 * r, 40 * r * 1.16))

print("\n=== G3 PoC 8건은 얼마인가 (상한 $20) ===")
for 해상도 in ("Seedance 480p", "Seedance 720p", "PixVerse (해상도 미확인)"):
    for r in (2.0, 2.5):
        c = 8 * r * 값[해상도]
        print("  %-24s 다시뽑기 %.1f배 → $%5.1f  %s"
              % (해상도, r, c, "OK" if c <= 20 else "**넘는다**"))
